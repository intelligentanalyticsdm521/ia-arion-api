/**
 * Extract the page engine's OWN widget controls for D-165's pin test.
 *
 *   node scripts/dev/extract-widget-controls.mjs
 *
 * §11.13.3 says the website "maps every standard kind to Elementor's widgetType
 * 1:1 with Elementor's own settings keys … one table, tested against the
 * machine file". This writes the extract that test reads, for exactly the
 * widget types `elementorWidgets.js` can publish — no more, so the fixture
 * stays small enough to read.
 *
 * THE KEYS ARE NOT TYPED IN HERE, and that is the whole point: the script runs
 * every row's own `settings()` over a maximal props object, collects the keys
 * that really come out, and then asks the machine file whether each one is a
 * control that widget has. A key the engine does not have makes this script
 * FAIL rather than write a fixture that would bless it.
 *
 * Source: BUILDER_WIDGET_CATALOG_2026-09-17.pro.json (the Pro registry export
 * — it is a superset of the free one, so one file answers for both). Override
 * with IA_CATALOG_PRO_JSON.
 */
import { writeFileSync, readFileSync, existsSync } from 'node:fs';
import path from 'node:path';

import { ELEMENTOR_WIDGETS, MAXIMAL_WIDGET_PROPS, WIDGET_CTX, SETTINGS_NOT_CONTROLS }
  from '../../test/fixtures/widget-controls-input.mjs';
import { iaProductOf } from '../../lib/websiteBuilder/elementorWidgets.js';

const iaTier = (tier) => !!iaProductOf(tier);

const MACHINE = process.env.IA_CATALOG_PRO_JSON
  || 'C:/dev/claude code/overnight-report/BUILDER_WIDGET_CATALOG_2026-09-17.pro.json';

if (!existsSync(MACHINE)) {
  console.error(`The machine file is not where this script looked:\n  ${MACHINE}\n`
    + 'Pass IA_CATALOG_PRO_JSON=<path to BUILDER_WIDGET_CATALOG_2026-09-17.pro.json>.');
  process.exit(1);
}

const registry = JSON.parse(readFileSync(MACHINE, 'utf8'));
const widgets = registry?.widgets;
if (!widgets || typeof widgets !== 'object') {
  console.error('That file has no `widgets` map — is it the registry export?');
  process.exit(1);
}

const out = { widgets: {}, unregistered: [] };
const missing = [];

for (const [kind, row] of Object.entries(ELEMENTOR_WIDGETS)) {
  /* A COMPOSITION publishes free widgets that already have their own rows, so
     there is nothing of its own to pin here. */
  if (row.node || !row.settings) continue;
  const widgetType = row.widgetType;
  const engine = widgets[widgetType];
  if (!engine) {
    /**
     * A WIDGET OF OURS THAT NO SITE REGISTERS YET.
     *
     * `catalog_card` publishes `ia_product_cards`, which the plugin has not
     * registered (stream D said so and the handoff asks for it). That is not
     * a mistake to hide: it is recorded here, and the test then insists the
     * row has a FALLBACK, so the page still shows a visitor a real price.
     */
    if (iaTier(row.tier)) { out.unregistered.push({ kind, widgetType, hasFallback: !!row.fallback }); continue; }
    missing.push(`${kind}: the engine has no widget called "${widgetType}"`);
    continue;
  }

  let emitted;
  try { emitted = row.settings(MAXIMAL_WIDGET_PROPS, WIDGET_CTX); }
  catch (e) { missing.push(`${kind}: settings() threw — ${e.message}`); continue; }

  const keys = Object.keys(emitted).filter((k) => !SETTINGS_NOT_CONTROLS.includes(k));
  const unknown = keys.filter((k) => !engine.controls?.[k]);
  if (unknown.length) { missing.push(`${kind} (${widgetType}): not controls of that widget — ${unknown.join(', ')}`); continue; }

  out.widgets[widgetType] = {
    title: engine.title,
    /* Every control this emitter can write, with the option list the engine
       offers for it when it has one. The test uses the list to refuse a value
       the control would drop. */
    controls: Object.fromEntries(keys.map((k) => {
      const c = engine.controls[k];
      return [k, {
        type: c.type,
        ...(c.options && !Array.isArray(c.options) ? { options: Object.keys(c.options) } : {}),
        ...(c.repeater_fields ? { repeater_fields: Object.keys(c.repeater_fields) } : {}),
      }];
    })),
  };
}

if (missing.length) {
  console.error('Refusing to write a fixture that blesses a key the page engine does not have:\n  '
    + missing.join('\n  '));
  process.exit(1);
}

out.note = 'Generated by scripts/dev/extract-widget-controls.mjs from '
  + 'BUILDER_WIDGET_CATALOG_2026-09-17.pro.json (Elementor 4.1.4 free + Pro 4.1.1, read off the live '
  + 'IA site 2026-09-17). Regenerate when the emitter gains a key or the engine is upgraded, and read '
  + 'the diff — a fixture regenerated without looking at is a test that agrees with whatever you did.';

const dest = path.join(process.cwd(), 'test', 'fixtures', 'elementor-widget-controls.json');
writeFileSync(dest, `${JSON.stringify(out, null, 2)}\n`);
console.log(`wrote ${Object.keys(out.widgets).length} widget types to ${dest}`);
