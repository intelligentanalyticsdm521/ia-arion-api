/** Every control key a widget has, out of the catalogue. `null` = not in it. */
function controlsOf(file, widgetType) {
  if (!existsSync(file)) return undefined;
  const reg = JSON.parse(readFileSync(file, 'utf8'));
  const w = reg?.widgets?.[widgetType];
  if (!w) return null;
  const cs = w.controls || {};
  return Array.isArray(cs) ? cs.map((c) => c.name) : Object.keys(cs);
}

