// test/families-f8-contact-furniture.test.mjs — what F8 publishes to a website.
//
// B-168 §C.1. The family's own test on the PUBLISHING side. The shared
// `website-builder-families.test.js` asks that every family's rows are
// complete; this asks the question that actually costs a client money:
//
//   **is every key we publish a control the page engine really has?**
//
// A key the engine does not have is dropped silently on publish. The page
// comes back green, the author's change is gone, and nobody is told — the
// `reference_catch_swallow_report_success` pattern with a settings object
// instead of a try/catch.
//
// ── WHY THIS READS THE MACHINE FILE AND NOT `elementor-widget-controls.json` ─
// That fixture is a small EXTRACT, generated by
// `scripts/dev/extract-widget-controls.mjs` for exactly the widget types the
// pre-family catalogue could publish. Regenerating it to add `login` and
// `nav-menu` would also record `mega-menu` under `unregistered`, and the
// shared test insists every unregistered row has a fallback — which `mega-menu`
// deliberately has not (a fake menu is worse than a refusal). So this file goes
// to the same source that fixture is cut from, with the same environment
// override the generator uses, and says so out loud rather than regenerating a
// shared fixture out from under nine other agents.
//
// ── THE MUTATIONS, run by EXECUTING the emitters, then restored ────────────
//   A. `show_lost_password` → `show_lost_passwordx` in emitters.js  → "every
//      key F8 publishes is a real control" red naming login and the key.
//   B. `widgetType: 'nav-menu'` → `'navmenu'`                        → same
//      test red: *not a widget in the catalogue*.
//   C. `choice(p.pointer, NAV_POINTERS, 'underline')` → `text(p.pointer)` →
//      "a value the control does not offer never leaves" red.
//   All three restored and the suite re-run green.
import { test, describe } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync, existsSync } from 'node:fs';

import { EMITTERS } from '../lib/websiteBuilder/families/f8-contact-furniture/emitters.js';
import { ELEMENTOR_WIDGETS, PRO } from '../lib/websiteBuilder/elementorWidgets.js';
/* Keys we write that are OURS, not the page engine's — the form-purpose stamp
   and the CSS classes `formPurpose.js` owns. One list, shared with the pin
   extractor, so this test and that script cannot disagree about which keys are
   controls. */
import { SETTINGS_NOT_CONTROLS } from './fixtures/widget-controls-input.mjs';

const MACHINE = process.env.IA_CATALOG_PRO_JSON
  || 'C:/dev/claude code/overnight-report/BUILDER_WIDGET_CATALOG_2026-09-17.pro.json';
const FREE_MACHINE = process.env.IA_CATALOG_FREE_JSON
  || 'C:/dev/claude code/overnight-report/BUILDER_WIDGET_CATALOG_2026-09-17.elementor.json';

/** Every control key a widget has, out of the catalogue. `null` = not in it. */
function controlsOf(file, widgetType) {
  if (!existsSync(file)) return undefined;
  const reg = JSON.parse(readFileSync(file, 'utf8'));
  const w = reg?.widgets?.[widgetType];
  if (!w) return null;
  const cs = w.controls || {};
  return Array.isArray(cs) ? cs.map((c) => c.name) : Object.keys(cs);
}

/* A maximal props object per kind: every control this family offers, filled
   in. Running the emitter on DEFAULTS only would miss every key that is spread
   conditionally, which is most of the style half. */
const FILLED = {
  login: {
    show_labels: 'yes', input_size: 'lg', button_text: 'Sign in', button_size: 'md',
    align: 'center', show_lost_password: 'yes', show_remember_me: 'yes',
    show_logged_in_message: 'yes',
    redirect_after_login: 'yes', redirect_url: 'https://example.org/account',
    redirect_after_logout: 'yes', redirect_logout_url: 'https://example.org/',
    row_gap: 18, links_color: '#0B1C24', label_color: '#5A7A8A',
    field_text_color: '#0B1C24', field_background_color: '#ffffff', field_border_color: '#CBD5E1',
    button_text_color: '#ffffff', button_background_color: '#1D7A8C', button_border_color: '#1D7A8C',
  },
  nav_menu: {
    menu: 'main-menu', menu_name: 'Primary', layout: 'vertical', align_items: 'center',
    pointer: 'framed', dropdown: 'mobile', full_width: 'yes', text_align: 'center',
    toggle: 'burger', toggle_align: 'right',
    color_menu_item: '#0B1C24', pointer_color_menu_item_hover: '#1D7A8C',
    menu_space_between: 28, padding_horizontal_menu_item: 14, padding_vertical_menu_item: 10,
    border_radius_menu_item: 6, color_dropdown_item: '#0B1C24',
    background_color_dropdown_item: '#F8FAFC', toggle_color: '#0B1C24',
    toggle_background_color: '#ffffff', toggle_size: 22,
  },
  mega_menu: {},
};

describe('f8-contact-furniture publishes only real controls', () => {
  test('the machine file is where this test thinks it is', () => {
    // A skipped check that looks like a pass is the failure mode this guards.
    assert.ok(existsSync(MACHINE),
      `The Elementor Pro catalogue is not at:\n  ${MACHINE}\n`
      + 'Pass IA_CATALOG_PRO_JSON, the way scripts/dev/extract-widget-controls.mjs does.');
  });

  for (const [kind, row] of Object.entries(EMITTERS)) {
    test(`${kind} → “${row.widgetType}”: every key is a control the engine has`, () => {
      const pro = controlsOf(MACHINE, row.widgetType);
      const free = controlsOf(FREE_MACHINE, row.widgetType);
      const keys = pro && pro.length ? pro : (free && free.length ? free : null);

      if (!keys) {
        /* `mega-menu`. It is absent from the Pro scrape entirely and carries
           `controls: {}` in the free one, so there is nothing to check against.
           The honest assertion is the ABSENCE: we publish no settings for it
           rather than inventing one. One fresh scrape closes this. */
        assert.deepEqual(row.settings(FILLED[kind] || {}, {}), {},
          `${row.widgetType}: neither catalogue carries a control for this widget, so nothing `
          + 'may be published for it until somebody scrapes it again');
        return;
      }

      const legal = new Set(keys);
      for (const props of [{}, FILLED[kind] || {}]) {
        const emitted = Object.keys(row.settings(props, {})).filter((k) => !SETTINGS_NOT_CONTROLS.includes(k));
        const bad = emitted.filter((k) => !legal.has(k) && !legal.has(k.replace(/_(tablet|mobile)$/, '')));
        assert.deepEqual(bad, [],
          `${row.widgetType}: the page engine has no control called ${bad.join(', ')}, so it drops `
          + 'the key on publish and the author\'s change does nothing on the live page');
      }
    });
  }

  test('every F8 row is Pro, and the catalogue agrees', () => {
    const reg = JSON.parse(readFileSync(MACHINE, 'utf8'));
    for (const [kind, row] of Object.entries(EMITTERS)) {
      assert.equal(row.tier, PRO, `${kind} must need a plan above ARION Lite`);
      const w = reg.widgets[row.widgetType];
      if (!w) continue; // mega-menu; recorded above.
      assert.ok((w.categories || []).includes('pro-elements'),
        `${row.widgetType} is no longer in the engine's pro-elements group — re-read the tier`);
    }
  });

  test('a locked F8 widget is refused by name, or swapped for something real', () => {
    /* Two outcomes, never a third: publish the widget, or refuse it BY NAME —
       unless the row carries a FALLBACK, and then the sentence the client reads
       and the node we publish have to agree. `form` is the only one with a
       fallback (our own shortcode on an ARION Lite site) and it carries both
       halves. `login` and `nav_menu` have none on purpose: a picture of a
       sign-in box or a fake menu is the blank band with a green toast over it. */
    for (const [kind, row] of Object.entries(EMITTERS)) {
      assert.ok(row.label, `${kind} has no label, so a refusal could not name it`);
      if (!row.fallback) continue;
      assert.equal(typeof row.fallbackFires, 'function',
        `${kind} has a fallback and no fallbackFires, so the pane cannot tell a client whether it fires`);
      assert.ok(row.swapSentence, `${kind} has a fallback and no sentence saying what was swapped`);
    }
    assert.deepEqual(Object.keys(EMITTERS).filter((k) => EMITTERS[k].fallback), ['form']);
  });

  test('the ARION Lite form fallback fires on PRESENCE of our shortcode, never on absence', () => {
    // `reference_absence_based_guards_fail_open`. Executed, not read.
    assert.equal(EMITTERS.form.fallbackFires({}), false);
    assert.equal(EMITTERS.form.fallbackFires({ iaShortcodes: [] }), false);
    assert.equal(EMITTERS.form.fallbackFires({ iaShortcodes: ['ia_book_now'] }), false);
    assert.equal(EMITTERS.form.fallbackFires({ iaShortcodes: ['ia_form'] }), true);
    assert.equal(EMITTERS.form.fallback({}, {}), null, 'a Lite site with no shortcode gets a refusal, not a picture');
    const node = EMITTERS.form.fallback({ purpose: 'contact' }, { iaShortcodes: ['ia_form'], nodeId: 'n1' });
    assert.equal(node.widgetType, 'shortcode');
    /* `normalizeFormPurpose` maps a contact form onto the platform's own word
       for it, `lead`, and the shortcode carries that word while the widget
       carries the same one in its keys — so a Lite form is typed by the same
       word as a Standard one and neither side has to guess. */
    assert.equal(node.settings.shortcode, '[ia_form purpose="lead" to=""]');
    assert.equal(node.settings._ia_form_purpose, 'lead');
  });
});

describe('f8-contact-furniture is wired in, and shadows nothing', () => {
  test('the one index really carries these rows through to the catalogue', () => {
    for (const kind of Object.keys(EMITTERS)) {
      assert.equal(ELEMENTOR_WIDGETS[kind], EMITTERS[kind],
        `${kind} is declared in the family and something else won in ELEMENTOR_WIDGETS`);
    }
  });

  test('the one F8 kind elementorWidgets.js still owns is NOT duplicated here', () => {
    /* `ELEMENTOR_WIDGETS` spreads the families FIRST and its own rows after, so
       a family row for a kind that file still declares would be shadowed and
       never called. `form` and `google_maps` are the two; they move here in the
       same pass the old rows are deleted (the handoff's "Land: delete these").
       The `form` row there is also the richer one — it carries the form-purpose
       stamp and the ARION Lite shortcode fallback. */
    for (const kind of ['map']) {
      assert.equal(EMITTERS[kind], undefined, `${kind} would be shadowed by elementorWidgets.js`);
      assert.ok(ELEMENTOR_WIDGETS[kind], `${kind} has vanished from the catalogue altogether`);
    }
  });
});

describe('f8-contact-furniture refuses a value the engine would drop', () => {
  test('a select never passes through a value the control does not offer', () => {
    const nav = EMITTERS.nav_menu.settings({
      layout: 'diagonal', pointer: 'sparkles', dropdown: 'watch',
      align_items: 'sideways', text_align: 'upwards', toggle: 'sprocket', toggle_align: 'behind',
    });
    assert.deepEqual(
      [nav.layout, nav.pointer, nav.dropdown, nav.align_items, nav.text_align, nav.toggle, nav.toggle_align],
      ['horizontal', 'underline', 'tablet', '', 'aside', 'burger', 'center']);
    const login = EMITTERS.login.settings({ input_size: 'enormous', button_size: 'titchy', align: 'sideways' });
    assert.deepEqual([login.input_size, login.button_size, login.align], ['sm', 'sm', '']);
  });

  test('a switch that defaults ON stays on when nobody has touched it', () => {
    const d = EMITTERS.login.settings({});
    assert.deepEqual(
      [d.show_remember_me, d.show_lost_password, d.show_logged_in_message, d.show_labels],
      ['yes', 'yes', 'yes', 'yes']);
    const off = EMITTERS.login.settings({ show_remember_me: false, show_lost_password: 'no' });
    assert.deepEqual([off.show_remember_me, off.show_lost_password], ['', '']);
  });

  test('a redirect URL never travels without the switch that turns it on', () => {
    const off = EMITTERS.login.settings({ redirect_url: 'https://example.org/account' });
    assert.equal('redirect_url' in off, false);
    const on = EMITTERS.login.settings({
      redirect_after_login: 'yes', redirect_url: 'https://example.org/account',
    });
    assert.equal(on.redirect_url.url, 'https://example.org/account');
    assert.equal(on.redirect_url.is_external, '');
  });

  test('WordPress Menu leaves `menu` out when the author has not chosen one', () => {
    // Elementor's `menu` names a menu registered on THAT site; the Portal does
    // not know them, so the panel offers no choice. Leaving the key out uses
    // the site's own default menu. Sending '' selects a menu called '' and the
    // visitor gets nothing.
    assert.equal('menu' in EMITTERS.nav_menu.settings({}), false);
    assert.equal(EMITTERS.nav_menu.settings({ menu: 'main-menu' }).menu, 'main-menu');
  });

  test('a colour nobody set is left to the theme, not overridden with nothing', () => {
    const bare = EMITTERS.login.settings({});
    for (const k of ['links_color', 'label_color', 'field_border_color', 'button_background_color']) {
      assert.equal(k in bare, false, `${k} was published as an empty override`);
    }
    assert.equal(EMITTERS.login.settings({ links_color: '#1D7A8C' }).links_color, '#1D7A8C');
  });

  test('a number reaches the engine in the shape its slider control reads', () => {
    const nav = EMITTERS.nav_menu.settings({ menu_space_between: 28 });
    assert.deepEqual(nav.menu_space_between, { unit: 'px', size: 28, sizes: [] });
  });
});
